import { chromium } from 'playwright';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
const DIST = process.argv[2];
const srv = http.createServer((req, res) => {
  let p = decodeURIComponent(req.url.split('?')[0]); if (p === '/') p = '/index.html';
  const f = path.join(DIST, p);
  if (!fs.existsSync(f)) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'Content-Type': f.endsWith('.js') ? 'text/javascript' : f.endsWith('.json') ? 'application/json' : 'text/html' });
  fs.createReadStream(f).pipe(res);
}).listen(4190);
const check = (cond, msg) => { console.log((cond ? 'PASS ' : 'FAIL ') + msg); if (!cond) process.exitCode = 1; };
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }).catch(() => chromium.launch());
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
await ctx.route('https://accounts.google.com/**', r => r.fulfill({ contentType: 'text/javascript', body: '' }));
await ctx.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }));
await ctx.route('https://*.openfoodfacts.org/**', r => r.fulfill({ status: 404, body: '{}' }));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
const nav = p.locator('.ft-bottom-nav');
await p.goto('http://localhost:4190/?tab=log'); await p.getByText('STRENGTH', { exact: true }).waitFor();
await p.getByRole('button', { name: 'FOOD', exact: true }).click();
await p.getByRole('button', { name: '+ Add to Lunch' }).click();
const search = p.getByLabel('Search foods');
const doneY = (await p.getByRole('button', { name: 'Done adding' }).boundingBox()).y, searchY = (await search.boundingBox()).y;
check(await p.getByRole('button', { name: 'Done adding' }).count() === 1 && doneY < searchY, 'Done adding sits at the top of the add box, above the search');
await p.locator('body').click({ position: { x: 5, y: 5 } }); await p.waitForTimeout(100);
check(await nav.isVisible(), 'bottom bar shows when nothing is being typed');
await search.tap(); await search.fill('chi');
await p.waitForTimeout(900);
const top = await search.evaluate(e => e.getBoundingClientRect().top);
check(top >= 0 && top < 120, 'tapping the search brings it to the top of the screen, results below it: ' + Math.round(top));
check(!(await nav.isVisible()), 'bottom bar hidden while the keyboard is up');
await p.screenshot({ path: 'food-typing.png' });
await search.evaluate(e => e.blur()); await p.waitForTimeout(150);
check(await nav.isVisible(), 'bottom bar back once typing stops');
await p.getByRole('button', { name: 'Done adding' }).click();
check(await p.getByLabel('Search foods').count() === 0 && await p.getByRole('button', { name: '+ Add to Lunch' }).count() === 1, 'Done adding at the top closes the add box');
// with a mouse nothing moves or hides
const d = await (await b.newContext({ viewport: { width: 1100, height: 800 } })).newPage();
await d.route('https://accounts.google.com/**', r => r.fulfill({ contentType: 'text/javascript', body: '' }));
await d.goto('http://localhost:4190/?tab=log'); await d.getByText('STRENGTH', { exact: true }).waitFor();
await d.getByRole('button', { name: 'FOOD', exact: true }).click();
await d.getByRole('button', { name: '+ Add to Lunch' }).click();
await d.getByLabel('Search foods').fill('chi'); await d.waitForTimeout(600);
check(await d.locator('.ft-bottom-nav').isVisible(), 'desktop: bottom bar stays while typing');
check(errs.length === 0, 'no page errors ' + JSON.stringify(errs));
await b.close(); srv.close();
